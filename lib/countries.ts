/** Lowercase without accents, so "mexico" finds "México". */
export function normalize(s: string): string {
  return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();
}

export function findCountry(nameOrCode: string): Country | undefined {
  const v = normalize(nameOrCode);
  return COUNTRIES.find(
    (c) =>
      c.code.toLowerCase() === v ||
      normalize(c.name_en) === v ||
      normalize(c.name_es) === v
  );
}
